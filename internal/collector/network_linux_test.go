func TestIsVirtualIface(t *testing.T) {
	virtual := []string{
		"",            // 空名视为虚拟
		"lo",          // 回环
		"docker0",     // 容器网桥
		"br-abc123",   // 自定义网桥
		"veth1a2b",    // 容器 veth pair
		"tun0",        // VPN 隧道
		"wg0",         // WireGuard
		"cloudflared", // Cloudflare 隧道
		"tailscale0",  // Tailscale
	}
	for _, iface := range virtual {
		if !isVirtualIface(iface) {
			t.Errorf("isVirtualIface(%q) = false, 期望 true（应被排除）", iface)
		}
	}

	physical := []string{"eth0", "ens3", "enp1s0", "wlan0"}
	for _, iface := range physical {
		if isVirtualIface(iface) {
			t.Errorf("isVirtualIface(%q) = true, 期望 false（物理网卡应统计）", iface)
		}
	}
}

func TestParseIptablesSave(t *testing.T) {
	output := `# Generated by ip6tables-save
*filter
:HELIOX_STATS - [0:0]
[10:1000] -A INPUT -j HELIOX_STATS
[1:100] -A HELIOX_STATS -p tcp -m tcp --sport 443
[2:200] -A HELIOX_STATS -p tcp -m tcp --dport 443
[3:300] -A HELIOX_STATS -p udp -m udp --sport 443
[4:400] -A HELIOX_STATS -p udp -m udp --dport 443
[5:500] -A HELIOX_STATS -p tcp -m tcp --sport 36890
[6:600] -A HELIOX_STATS -p tcp -m tcp --sport 8080
COMMIT
`
	targets := map[int]struct{}{443: {}, 36890: {}}
	got, err := parseIptablesSave(output, targets)
	if err != nil {
		t.Fatalf("parseIptablesSave 失败: %v", err)
	}
	if c, ok := got[443]; !ok || c.tx != 400 || c.rx != 600 {
		t.Errorf("443 = %+v (ok=%v), want tx=400 rx=600", c, ok)
	}
	// 36890 只有 sport 规则，方向不全不应收录，否则 RX 会被当成 0 写进快照
	if _, ok := got[36890]; ok {
		t.Error("方向不全的端口不应收录")
	}
	if _, ok := got[8080]; ok {
		t.Error("非目标端口不应收录")
	}
}

func TestAdvancePortPerFamily(t *testing.T) {
	c := &Collector{
		lastPortTx:  map[int]uint64{443: 1000},
		lastPortRx:  map[int]uint64{443: 2000},
		lastPortRaw: map[portFamilyKey]rawPortCounter{{familyV4, 443}: {tx: 100, rx: 200}},
	}
	reading := func(v4, v6 *rawPortCounter) map[string]map[int]rawPortCounter {
		r := map[string]map[int]rawPortCounter{}
		if v4 != nil {
			r[familyV4] = map[int]rawPortCounter{443: *v4}
		}
		if v6 != nil {
			r[familyV6] = map[int]rawPortCounter{443: *v6}
		}
		return r
	}

	// v6 首次出现只建基准，不把它已有的计数一次性计入
	c.advancePort(443, reading(&rawPortCounter{150, 250}, &rawPortCounter{9000, 9000}))
	if c.lastPortTx[443] != 1050 || c.lastPortRx[443] != 2050 {
		t.Fatalf("累计 = %d/%d, want 1050/2050", c.lastPortTx[443], c.lastPortRx[443])
	}

	// v6 某轮读不到：不能被当成计数器回退，下一轮读到时增量补齐
	c.advancePort(443, reading(&rawPortCounter{160, 260}, nil))
	c.advancePort(443, reading(&rawPortCounter{170, 270}, &rawPortCounter{9100, 9100}))
	if c.lastPortTx[443] != 1170 || c.lastPortRx[443] != 2170 {
		t.Fatalf("累计 = %d/%d, want 1170/2170", c.lastPortTx[443], c.lastPortRx[443])
	}

	// v4 计数器重置（规则重建）：从 0 重新开始计增量
	c.advancePort(443, reading(&rawPortCounter{5, 5}, &rawPortCounter{9100, 9100}))
	if c.lastPortTx[443] != 1175 || c.lastPortRx[443] != 2175 {
		t.Fatalf("累计 = %d/%d, want 1175/2175", c.lastPortTx[443], c.lastPortRx[443])
	}

	if c.advancePort(443, reading(nil, nil)) {
		t.Error("两个地址族都读不到时应返回 false")
	}
}
